# Two no's sum

a = int(input("a : "))
op = input("operator (+,-,*,/,%): ")
b = int(input("b : "))

if op == "+" :
    print(a+b)
elif op == "-":
    print(a-b)
elif op == "*":
    print(a*b)
elif op == "/":
    print(a/b)
elif op =="%" :
    print(a%b)
else :
    print("Invalid operator") 



